// parseRect 解析 "x0,y0,x1,y1,color" 字符串。
func parseRect(s string) ([4]int, RGB, error) {
	parts := splitComma(s)
	if len(parts) != 5 {
		return [4]int{}, RGB{}, fmt.Errorf("-rect 格式应为 x0,y0,x1,y1,color")
	}
	var nums [4]int
	for i := 0; i < 4; i++ {
		v, err := strconv.Atoi(strings.TrimSpace(parts[i]))
		if err != nil {
			return [4]int{}, RGB{}, fmt.Errorf("-rect 坐标需为整数: %s", parts[i])
		}
		nums[i] = v
	}
	c, err := parseColor(strings.TrimSpace(parts[4]))
	if err != nil {
		return [4]int{}, RGB{}, err
	}
	return nums, c, nil
}

func splitComma(s string) []string {
	out := []string{}
	cur := strings.Builder{}
	for _, r := range s {
		if r == ',' {
			out = append(out, cur.String())
			cur.Reset()
			continue
		}
		cur.WriteRune(r)
	}
	out = append(out, cur.String())
	return out
}

